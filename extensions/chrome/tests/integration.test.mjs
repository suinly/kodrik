import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,cp,readFile,writeFile,rm,mkdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {chromium,expect} from '../../../web/node_modules/@playwright/test/index.mjs';
import {startFixture,stopFixture} from '../../../web/tests/fixture-process.mjs';

test('extension sends context only on first message and serves agent requests with fresh context', {timeout:120000},async()=>{
  const dir=await mkdtemp(join(tmpdir(),'kodrik-extension-test-'));
  let context,server;
  try {
    const fixture=await startFixture();server=fixture.server;
    const base=fixture.url;
    const extension=join(dir,'extension');
    await cp(fileURLToPath(new URL('../',import.meta.url)),extension,{recursive:true});
    // A browser test pregrants only the fixture hosts; shipping manifest uses optional permissions.
    const manifest=JSON.parse(await readFile(join(extension,'manifest.json'),'utf8'));
    manifest.host_permissions=['http://127.0.0.1/*','https://docs.google.com/*'];
    await writeFile(join(extension,'manifest.json'),JSON.stringify(manifest));
    context=await chromium.launchPersistentContext(join(dir,'profile'),{headless:true,channel:'chromium',args:[`--disable-extensions-except=${extension}`,`--load-extension=${extension}`]});
    const worker=context.serviceWorkers()[0] || await context.waitForEvent('serviceworker');
    const extensionId=new URL(worker.url()).host;
    const login=await context.newPage();
    await login.goto(new URL('auth/login',base).href);
    await login.locator('input[type=password]').fill('preview-password');
    await login.locator('button[type=submit]').click();
    await expect(login.locator('input[type=password]')).toHaveCount(0);
    await worker.evaluate(server=>chrome.storage.local.set({server}),base);
    const article=await context.newPage();
    await article.route('http://127.0.0.1:19991/article',route=>route.fulfill({contentType:'text/html',body:'<title>Test article</title><article>ORIGINAL ARTICLE CONTENT</article>'}));
    await article.goto('http://127.0.0.1:19991/article');
    const panel=await context.newPage();
    await panel.setViewportSize({width:420,height:850});
    const owner=await worker.evaluate(async()=> (await chrome.tabs.query({})).find(tab=>tab.url==='http://127.0.0.1:19991/article').id);
    await panel.goto(`chrome-extension://${extensionId}/sidepanel.html?tab=${owner}`);
    const chat=panel.frameLocator('#chat');
    const input=chat.getByRole('textbox',{name:/^(Сообщение|Message)$/,exact:true});
    await expect(input).toBeEditable();
    await panel.waitForTimeout(700);
    await expect(panel.locator('#status')).toHaveText('');
    // Side panel focus doesn't activate a browser tab; keep the article active.
    await article.bringToFront();
    await input.fill('Объясни открытую статью');
    await panel.waitForTimeout(400);
    const sent=panel.waitForRequest(req=>req.method()==='POST' && req.url().endsWith('/api/chat/send'));
    await input.press('Enter');

    const request=await sent;
    assert.match(request.headers()['content-type'],/application\/json/);
    const payload=request.postDataJSON();
    assert.match(payload.browser_client_id,/^[0-9a-f-]{36}$/);
    assert.equal(payload.browser_context.source,'page');
    assert.match(payload.browser_context.text,/ORIGINAL ARTICLE CONTENT/);
    assert.ok(!payload.files?.length);
    const attachment=chat.getByTestId('tab-context');
    await expect(attachment).toHaveCount(1);
    await expect(chat.getByRole('switch',{name:'Включить контекст вкладки'})).toHaveCount(0);
    await expect(chat.getByTestId('browser-context')).toHaveCount(0);
    await attachment.getByRole('button').click();
    await expect(chat.getByRole('region',{name:'Содержимое вкладки'})).toContainText('ORIGINAL ARTICLE CONTENT');
    await attachment.getByRole('button').click();
    const settings=chat.getByRole('button',{name:'Настройки расширения',exact:true});
    const search=chat.getByRole('button',{name:/^(Найти в диалоге|Find in conversation)$/,exact:true});
    const menu=chat.getByRole('button',{name:/^(Показать диалоги|Show conversations)$/,exact:true});
    const header=chat.locator('header').last();
    await expect(header.locator('h1')).toHaveCount(0);
    await settings.click();
    await expect(panel.getByRole('dialog')).toBeVisible();
    await expect(panel.locator('#server')).toHaveValue(base);
    await panel.getByRole('button',{name:'Закрыть настройки',exact:true}).click();
    await expect(panel.getByRole('dialog')).not.toBeVisible();
    const settingsBox=await settings.boundingBox(),searchBox=await search.boundingBox(),menuBox=await menu.boundingBox();
    assert.ok(Math.abs(settingsBox.y-searchBox.y)<4 && settingsBox.x<searchBox.x);
    assert.ok(Math.abs(menuBox.y-settingsBox.y)<6);
    await expect(chat.getByRole('link',{name:'browser-tab.txt',exact:true})).toHaveCount(0);
    await expect(input).toBeEditable();
    await expect(chat.getByText('Привет!',{exact:true})).toBeVisible();
    await article.locator('article').evaluate(el=>el.textContent='UPDATED ARTICLE CONTENT');
    await article.bringToFront();
    await input.fill('А сейчас?');
    const second=panel.waitForRequest(req=>req.method()==='POST' && req.url().endsWith('/api/chat/send'));
    await input.press('Enter');
    const secondPayload=(await second).postDataJSON();
    assert.equal(secondPayload.browser_context,null);
    assert.equal(secondPayload.browser_client_id,payload.browser_client_id);
    // Simulate only the server request boundary; real iframe bridge and MV3 capture remain live.
    let requested=false;
    await panel.route('**/api/chat/browser-context**',route=>{
      if(route.request().method()==='GET') {
        const request_id=requested ? null : 'agent-request';requested=true;
        return route.fulfill({json:{request_id}});
      }
      return route.fulfill({json:{ok:true}});
    });
    const agentResult=await panel.waitForRequest(req=>req.method()==='POST' && req.url().includes('/api/chat/browser-context'));
    assert.equal(agentResult.postDataJSON().request_id,'agent-request');
    assert.match(agentResult.postDataJSON().context.text,/UPDATED ARTICLE CONTENT/);
    await panel.unroute('**/api/chat/browser-context**');
    let commandDone=false;
    await panel.route('**/api/chat/browser-command**',route=>{
      if(route.request().method()==='GET') return route.fulfill({json:{request_id:commandDone?null:'snapshot-request',command:commandDone?null:{action:'snapshot'}}});
      commandDone=true;return route.fulfill({json:{ok:true}});
    });
    const snapshotReply=await panel.waitForRequest(req=>req.method()==='POST' && req.url().includes('/api/chat/browser-command'));
    const freshSnapshot=snapshotReply.postDataJSON().result;
    assert.ok(freshSnapshot.snapshot_id);
    assert.match(freshSnapshot.text,/UPDATED ARTICLE CONTENT/);
    commandDone=false;
    await panel.unroute('**/api/chat/browser-command**');
    await panel.route('**/api/chat/browser-command**',route=>{
      if(route.request().method()==='GET') return route.fulfill({json:{request_id:commandDone?null:'evaluate-request',command:commandDone?null:{action:'evaluate',snapshot_id:freshSnapshot.snapshot_id,code:'return document.title;'}}});
      commandDone=true;return route.fulfill({json:{ok:true}});
    });
    const evaluation=panel.waitForRequest(req=>req.method()==='POST' && req.url().includes('/api/chat/browser-command'));
    // The native extension confirmation is outside the chat iframe.
    await panel.getByRole('dialog',{name:/действ|управл|подтвер/i}).getByRole('button',{name:/Разрешить|Выполнить|Подтвердить/i}).click();
    assert.equal((await evaluation).postDataJSON().result,'Test article');
    await panel.unroute('**/api/chat/browser-command**');
    await expect(attachment).toHaveCount(1);
    await attachment.getByRole('button').click();
    await expect(chat.getByRole('region',{name:'Содержимое вкладки'})).toContainText('UPDATED ARTICLE CONTENT');
    await expect(chat.getByRole('region',{name:'Содержимое вкладки'})).not.toContainText('ORIGINAL ARTICLE CONTENT');
    await attachment.getByRole('button').click();
    await menu.click();
    await chat.getByRole('button',{name:/^(Новый диалог|New conversation)$/,exact:true}).first().click();
    await input.fill('Новый диалог о вкладке');
    await article.bringToFront();
    const third=panel.waitForRequest(req=>req.method()==='POST' && req.url().endsWith('/api/chat/send'));
    await input.press('Enter');
    assert.match((await third).postDataJSON().browser_context.text,/UPDATED ARTICLE CONTENT/);
    await expect(attachment).toHaveCount(1);
    await expect.poll(()=>worker.evaluate(async id=>(await chrome.storage.session.get(`tab-chat:${id}`))[`tab-chat:${id}`]?.path,owner)).toMatch(/\/app\/chat\/.+/);
    const mapping=await worker.evaluate(async id=>(await chrome.storage.session.get(`tab-chat:${id}`))[`tab-chat:${id}`],owner);
    assert.match(mapping.path,/\/app\/chat\/.+/);
    await panel.reload();
    await expect(input).toBeEditable();
    await input.fill('После перезагрузки');
    const restored=panel.waitForRequest(req=>req.method()==='POST' && req.url().endsWith('/api/chat/send'));
    await input.press('Enter');
    assert.equal((await restored).postDataJSON().browser_context,null);
    await expect(chat.getByTestId('tab-context')).toHaveCount(1);
    const other=await context.newPage();
    await other.goto(`chrome-extension://${extensionId}/sidepanel.html?tab=999999`);
    await expect(other.frameLocator('#chat').getByTestId('browser-context')).toHaveCount(0);
    await other.close();
    await panel.setViewportSize({width:420,height:850});
    await panel.waitForTimeout(700);
    await mkdir(join(tmpdir(),'kodrik-sidebar-check'),{recursive:true});
    await panel.screenshot({path:join(tmpdir(),'kodrik-sidebar-check/sidebar.png')});
    // Exercise native export through real MV3 injection, bridge, multipart admission and history.
    await article.route('https://docs.google.com/document/d/test-document/**', route=> {
      const url=new URL(route.request().url());
      return route.fulfill(url.pathname.endsWith('/export') ? {contentType:'text/markdown',body:'# Exported document\nNATIVE EXPORT CONTENT'} : {contentType:'text/html',body:'<title>Workspace report</title><main>EDITOR SHELL MUST NOT BE SENT</main>'});
    });
    await article.goto('https://docs.google.com/document/d/test-document/edit?tab=t.1');
    await panel.reload();
    await expect(input).toBeEditable();
    await menu.click();
    await chat.getByRole('button',{name:/^(Новый диалог|New conversation)$/,exact:true}).first().click();
    await input.fill('Прочти документ');
    const exported=panel.waitForRequest(req=>req.method()==='POST' && req.url().endsWith('/api/chat/send'));
    await input.press('Enter');
    const exportedRequest=await exported;
    assert.match(exportedRequest.headers()['content-type'],/multipart\/form-data/);
    const exportedLink=chat.getByRole('link',{name:'Workspace report.md',exact:true});
    await expect(exportedLink).toBeVisible();
    const documentURL=await exportedLink.evaluate(el=>el.href);
    const storedDocument=await context.request.get(documentURL);
    assert.equal(storedDocument.ok(),true);
    assert.equal(await storedDocument.text(),'# Exported document\nNATIVE EXPORT CONTENT');
    const pdfBytes='%PDF-1.4\n1 0 obj<</Type/Catalog/Pages 2 0 R>>endobj\n2 0 obj<</Type/Pages/Count 0/Kids[]>>endobj\ntrailer<</Root 1 0 R>>\n%%EOF';
    await article.route('http://127.0.0.1:19991/report.pdf',route=>route.fulfill({contentType:'application/pdf',body:pdfBytes}));
    await article.goto('http://127.0.0.1:19991/report.pdf');
    await panel.reload();
    await expect(input).toBeEditable();
    await menu.click();
    await chat.getByRole('button',{name:/^(Новый диалог|New conversation)$/,exact:true}).first().click();
    await input.fill('Прочти PDF');
    const pdfSent=panel.waitForRequest(req=>req.method()==='POST' && req.url().endsWith('/api/chat/send'));
    await input.press('Enter');
    assert.match((await pdfSent).headers()['content-type'],/multipart\/form-data/);
    const pdfLink=chat.getByRole('link',{name:/\.pdf$/,exact:false});
    await expect(pdfLink).toBeVisible();
    const savedPDF=await context.request.get(await pdfLink.evaluate(el=>el.href));
    assert.equal(savedPDF.ok(),true);
    assert.equal(await savedPDF.text(),pdfBytes);


  } finally {await context?.close();await stopFixture(server);await rm(dir,{recursive:true,force:true});}
});
